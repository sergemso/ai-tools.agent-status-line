#!/usr/bin/env node
/**
 * Render a captured terminal pane (tmux `capture-pane -e -p`) to an SVG.
 *
 * Unlike render-screenshots.mjs, which runs the binary on a payload, these
 * come from the real agent CLIs: start the agent in tmux with the status line
 * configured, capture the pane, keep the lines worth showing in
 * docs/captures/<name>.ansi, then run this.
 *
 * Usage: node scripts/render-live-capture.mjs <capture.ansi> <out.svg> "<window title>"
 *
 * Needs `npm run build:core` first (for the cell-width table).
 */

import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath, pathToFileURL } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const { visibleWidth } = await import(pathToFileURL(join(ROOT, "packages/core/dist/index.js")).href);

const [, , inFile, outFile, heading = "Terminal"] = process.argv;
if (!inFile || !outFile) {
  console.error('usage: render-live-capture.mjs <capture.ansi> <out.svg> "<window title>"');
  process.exit(1);
}

const BASIC = ["#484f58", "#f85149", "#3fb950", "#d29922", "#58a6ff", "#bc8cff", "#39c5cf", "#c9d1d9",
               "#8b949e", "#ff7b72", "#56d364", "#e3b341", "#79c0ff", "#d2a8ff", "#56d4dd", "#f0f6fc"];
const DEFAULT_FG = "#c9d1d9", PAGE_BG = "#0d1117";
const CW = 8.4, LINE_H = 20;

function xterm(n) {
  if (n < 16) return BASIC[n];
  if (n >= 232) { const v = 8 + (n - 232) * 10; return `rgb(${v},${v},${v})`; }
  const k = n - 16, lv = (x) => (x === 0 ? 0 : 55 + x * 40);
  return `rgb(${lv(Math.floor(k / 36))},${lv(Math.floor(k / 6) % 6)},${lv(k % 6)})`;
}

function parse(line) {
  const segs = [];
  let st = { fg: null, bg: null, dim: false, bold: false }, buf = "";
  const flush = () => { if (buf) { segs.push({ text: buf, ...st }); buf = ""; } };
  for (let i = 0; i < line.length; ) {
    const m = /^\x1b\[([0-9;:]*)m/.exec(line.slice(i));
    if (m) {
      flush();
      const p = (m[1] || "0").split(/[;:]/).map(Number);
      for (let j = 0; j < p.length; j++) {
        const c = p[j];
        if (c === 0) st = { fg: null, bg: null, dim: false, bold: false };
        else if (c === 1) st.bold = true;
        else if (c === 2) st.dim = true;
        else if (c === 22) { st.dim = false; st.bold = false; }
        else if (c === 39) st.fg = null;
        else if (c === 49) st.bg = null;
        else if (c >= 30 && c <= 37) st.fg = BASIC[c - 30];
        else if (c >= 90 && c <= 97) st.fg = BASIC[c - 90 + 8];
        else if (c >= 40 && c <= 47) st.bg = BASIC[c - 40];
        else if (c === 38 || c === 48) {
          const key = c === 38 ? "fg" : "bg";
          if (p[j + 1] === 5) { st[key] = xterm(p[j + 2]); j += 2; }
          else if (p[j + 1] === 2) { st[key] = `rgb(${p[j + 2]},${p[j + 3]},${p[j + 4]})`; j += 4; }
        }
      }
      i += m[0].length;
    } else if (line[i] === "\x1b") {
      const o = /^\x1b\[[0-9;?]*[A-Za-z]/.exec(line.slice(i));
      flush();
      i += o ? o[0].length : 1;
    } else { buf += line[i]; i++; }
  }
  flush();
  return segs;
}

const esc = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const lines = readFileSync(join(ROOT, inFile), "utf8").split("\n");
while (lines.length && !lines[lines.length - 1].trim()) lines.pop();

const PAD = 20, TOP = 52;
let maxCols = 0, body = "", rects = "";
lines.forEach((line, row) => {
  const y = TOP + row * LINE_H + 14;
  let col = 0;
  for (const s of parse(line)) {
    const w = visibleWidth(s.text);
    if (s.bg) rects += `<rect x="${(PAD + col * CW).toFixed(1)}" y="${y - 15}" width="${(w * CW).toFixed(1)}" height="${LINE_H}" fill="${s.bg}"/>\n`;
    if (s.text.trim()) {
      const attrs = `fill="${s.fg ?? DEFAULT_FG}"${s.dim ? ' fill-opacity="0.55"' : ""}${s.bold ? ' font-weight="700"' : ""}`;
      body += `<text x="${(PAD + col * CW).toFixed(1)}" y="${y}" ${attrs} xml:space="preserve">${esc(s.text)}</text>\n`;
    }
    col += w;
  }
  maxCols = Math.max(maxCols, col);
});

const width = Math.ceil(PAD * 2 + maxCols * CW), height = TOP + lines.length * LINE_H + 12;
const MONO = "ui-monospace,'SF Mono',Menlo,Consolas,'DejaVu Sans Mono','Liberation Mono','Noto Sans Symbols 2','Segoe UI Symbol','Apple Symbols',monospace";
const SANS = "-apple-system,'Segoe UI',Helvetica,Arial,sans-serif";
writeFileSync(join(ROOT, outFile), `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="t" font-size="14">
<title id="t">${esc(heading)}</title>
<!-- Generated by scripts/render-live-capture.mjs from a tmux capture of the real CLI; regenerate rather than hand-edit. -->
<rect width="${width}" height="${height}" rx="10" fill="${PAGE_BG}" stroke="#30363d"/>
<rect width="${width}" height="34" rx="10" fill="#161b22"/><rect y="24" width="${width}" height="10" fill="#161b22"/>
<circle cx="22" cy="17" r="6" fill="#ff5f56"/><circle cx="42" cy="17" r="6" fill="#ffbd2e"/><circle cx="62" cy="17" r="6" fill="#27c93f"/>
<text x="${width / 2}" y="22" text-anchor="middle" font-family="${SANS}" font-size="13" fill="#6e7681">${esc(heading)}</text>
${rects}<g font-family="${MONO}">
${body}</g>
</svg>
`);
console.log(`wrote ${outFile}`);
